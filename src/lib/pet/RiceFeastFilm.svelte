<!--
  DeepSeek 大肥鱼 rice feast for the transparent desktop window. [FRONTEND]

  The H3 clip is chroma-keyed, trimmed to 60 frames and packed into one
  horizontal WebP strip (`scripts/prepare-pet-assets.py` builds the still
  assets; this strip is generated by the H3 experiment documented in
  `docs/plans/desktop-pet.md`). The frame is advanced with a small rAF loop
  instead of CSS `steps()` so the strip stays aligned at every container size.
  The strip is silent and transparent, so the desktop keeps its wallpaper and
  the window stays a pet rather than a video player.

  A missing sheet, or reduced motion, falls back to the supplied cutout with
  the pure-CSS steam/grain animation.
-->
<script lang="ts">
  import { onMount } from 'svelte';
  import RiceFeast from './RiceFeast.svelte';

  interface Props {
    /** Run the loop; when false the first frame is held. */
    active?: boolean;
    /** Accessible description, normally "… is eating a bowl of rice". */
    label: string;
    frames?: number;
    fps?: number;
    src?: string;
  }

  let {
    active = true,
    label,
    frames = 60,
    fps = 12,
    src = '/pet/deepseek-feast-sheet.webp',
  }: Props = $props();

  let frame = $state(0);
  let reduced = $state(false);
  let failed = $state(false);

  onMount(() => {
    const query = window.matchMedia('(prefers-reduced-motion: reduce)');
    reduced = query.matches;
    const change = () => (reduced = query.matches);
    query.addEventListener('change', change);
    return () => query.removeEventListener('change', change);
  });

  $effect(() => {
    if (!active || reduced || failed || frames < 2) {
      frame = 0;
      return;
    }
    const period = 1000 / fps;
    let raf = 0;
    let start = performance.now();
    let last = 0;
    const tick = (now: number) => {
      const next = Math.floor((now - start) / period) % frames;
      if (next !== last) {
        last = next;
        frame = next;
      }
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  });
</script>

{#if failed || reduced}
  <RiceFeast active={active && !reduced} {label} />
{:else}
  <span
    class="film"
    class:active
    role="img"
    aria-label={label}
    data-testid="rice-feast"
    data-kind="film"
    data-src={src}
    style:--frames={frames}
  >
    <span class="window" aria-hidden="true">
      <img
        class="sheet"
        {src}
        alt=""
        draggable="false"
        style:transform={`translateX(${(-frame * 100) / frames}%)`}
        onerror={() => (failed = true)}
      />
    </span>
  </span>
{/if}

<style>
  .film {
    position: relative;
    display: block;
    width: 100%;
    height: 100%;
    aspect-ratio: 1;
    isolation: isolate;
  }

  .window {
    position: absolute;
    inset: 0;
    display: block;
    overflow: hidden;
    filter: drop-shadow(0 0.18rem 0.3rem rgb(8 18 34 / 0.24));
  }

  .sheet {
    display: block;
    width: calc(var(--frames) * 100%);
    max-width: none;
    height: 100%;
    object-fit: fill;
    user-select: none;
    -webkit-user-drag: none;
    will-change: transform;
  }

  @media (prefers-reduced-motion: reduce) {
    .film {
      display: none;
    }
  }
</style>
